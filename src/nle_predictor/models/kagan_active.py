"""
Kagan Active Dimer Model for Non-Linear Effects in Asymmetric Catalysis.
Reference: H. B. Kagan et al., J. Am. Chem. Soc. 1989, 111, 4826-4833.
"""

import logging
from typing import Optional, Sequence, Tuple

import numpy as np

from nle_predictor.core.constants import DEFAULT_TEMP, GAS_CONSTANT_R
from nle_predictor.core.types import NLESimulationResult
from nle_predictor.models.base import NLEModel
from nle_predictor.models.kagan_ml2 import NLECalculator

logger = logging.getLogger("NLE_Predictor")


class KaganActiveDimerModel(NLEModel):
    """
    Extends Kagan's ML2 model to allow homochiral and heterochiral dimers
    to possess intrinsic catalytic reactivity alongside the monomer.

    Parameters
    ----------
    temp : float
        Temperature in Kelvin.
    g : float
        Relative reactivity of homochiral dimer vs monomer (k_dimer / k_monomer).
    g_prime : float
        Relative reactivity of heterochiral (RS) dimer vs monomer (k_hetero / k_monomer).
    ee_0 : float
        Intrinsic enantiomeric excess generated by pure monomer (default 1.0 = 100%).
    ee_d : float
        Intrinsic enantiomeric excess generated by pure homochiral dimer (default 1.0 = 100%).
    """
    def __init__(
        self,
        temp: float = DEFAULT_TEMP,
        g: float = 0.0,
        g_prime: float = 0.0,
        ee_0: float = 1.0,
        ee_d: float = 1.0,
    ):
        if temp <= 0:
            raise ValueError("Temperature must be greater than zero Kelvin.")
        if g < 0 or g_prime < 0:
            raise ValueError("Relative rate constants g and g_prime must be non-negative.")
        if not (-1.0 <= ee_0 <= 1.0) or not (-1.0 <= ee_d <= 1.0):
            raise ValueError("Intrinsic ee values must lie within [-1.0, +1.0].")

        self.temp = temp
        self.g = g
        self.g_prime = g_prime
        self.ee_0 = ee_0
        self.ee_d = ee_d
        self._calculator = NLECalculator(temp=temp)

    def calculate_rates(
        self,
        mr: float,
        ms: float,
        k_homo: float,
        k_hetero: float,
        g: Optional[float] = None,
        g_prime: Optional[float] = None,
        ee_0: Optional[float] = None,
        ee_d: Optional[float] = None,
    ) -> Tuple[float, float, float]:
        """
        Compute instantaneous rates v_R, v_S, and resulting product ee.

        Returns
        -------
        Tuple[float, float, float]
            (v_R, v_S, ee_product)
        """
        g_val = self.g if g is None else g
        gp_val = self.g_prime if g_prime is None else g_prime
        e0_val = self.ee_0 if ee_0 is None else ee_0
        ed_val = self.ee_d if ee_d is None else ee_d

        d_rr = k_homo * (mr ** 2)
        d_ss = k_homo * (ms ** 2)
        d_rs = k_hetero * mr * ms

        # Monomer contributions (normalized k_M = 1.0)
        v_r_mono = 0.5 * (1.0 + e0_val) * mr + 0.5 * (1.0 - e0_val) * ms
        v_s_mono = 0.5 * (1.0 - e0_val) * mr + 0.5 * (1.0 + e0_val) * ms

        # Homochiral dimer contributions
        v_r_dim = 2.0 * g_val * (0.5 * (1.0 + ed_val) * d_rr + 0.5 * (1.0 - ed_val) * d_ss)
        v_s_dim = 2.0 * g_val * (0.5 * (1.0 - ed_val) * d_rr + 0.5 * (1.0 + ed_val) * d_ss)

        # Heterochiral (meso) dimer contribution (typically racemic product)
        v_meso = gp_val * d_rs

        v_r = v_r_mono + v_r_dim + v_meso
        v_s = v_s_mono + v_s_dim + v_meso
        v_tot = v_r + v_s

        if v_tot <= 1e-15:
            ee_p = 0.0
        else:
            ee_p = (v_r - v_s) / v_tot

        return v_r, v_s, float(ee_p)

    def simulate(
        self,
        ee_cat_range: Sequence[float],
        delta_g_kcal: Optional[float] = None,
        k_homo: float = 1e5,
        g: Optional[float] = None,
        g_prime: Optional[float] = None,
        ee_0: Optional[float] = None,
        ee_d: Optional[float] = None,
        delta_g: Optional[float] = None,
        **kwargs,
    ) -> NLESimulationResult:
        """Simulate product ee trajectory with active dimers."""
        dg_val = delta_g_kcal if delta_g_kcal is not None else (delta_g if delta_g is not None else 0.0)
        ee_cat = np.asarray(ee_cat_range, dtype=float)
        g_val = self.g if g is None else g
        gp_val = self.g_prime if g_prime is None else g_prime
        e0_val = self.ee_0 if ee_0 is None else ee_0
        ed_val = self.ee_d if ee_d is None else ee_d

        ratio = 2.0 * np.exp(-dg_val / (GAS_CONSTANT_R * self.temp))
        k_hetero = k_homo * ratio

        ee_prods = []
        monomers_r = []
        monomers_s = []

        for cat in ee_cat:
            mr, ms = self._calculator.solve_mass_balance(cat, k_homo, k_hetero)
            monomers_r.append(mr)
            monomers_s.append(ms)
            _, _, ee_p = self.calculate_rates(
                mr, ms, k_homo, k_hetero, g=g_val, g_prime=gp_val, ee_0=e0_val, ee_d=ed_val
            )
            ee_prods.append(ee_p)

        ee_prod_arr = np.array(ee_prods)
        diff = ee_prod_arr - ee_cat
        tol = 1e-6
        if np.max(diff) > tol:
            classification = "positive NLE"
        elif np.min(diff) < -tol:
            classification = "negative NLE"
        else:
            classification = "near-linear"

        product_at_50 = float(np.interp(0.5, ee_cat, ee_prod_arr))
        amplification = np.divide(
            ee_prod_arr[1:], ee_cat[1:], out=np.zeros_like(ee_prod_arr[1:]), where=ee_cat[1:] > 0
        )
        max_amp = float(np.max(amplification)) if len(amplification) > 0 else 1.0

        return NLESimulationResult(
            model_name="Kagan ML2 Active Dimer Model",
            ee_catalyst=ee_cat,
            ee_product=ee_prod_arr,
            monomers_r=np.array(monomers_r),
            monomers_s=np.array(monomers_s),
            classification=classification,
            product_at_50=product_at_50,
            max_amplification=max_amp,
            max_deviation_from_linearity=float(np.max(np.abs(diff))),
            metadata={
                "k_homo": k_homo,
                "k_hetero": k_hetero,
                "k_ratio": ratio,
                "delta_g_kcal": dg_val,
                "g": g_val,
                "g_prime": gp_val,
                "ee_0": e0_val,
                "ee_d": ed_val,
                "temperature_k": self.temp,
            },
        )
