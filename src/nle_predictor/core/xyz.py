"""
Molecular structure manipulation, XYZ file I/O, validation, and geometry analysis.
"""

import os
from collections import Counter
from typing import List

import numpy as np

from nle_predictor.core.constants import ATOMIC_WEIGHTS
from nle_predictor.core.types import XYZStructure


def validate_xyz_file(xyz_path: str) -> int:
    """
    Validate that an XYZ file exists, contains a valid atom count header,
    and has properly formatted coordinates for all atoms.

    Parameters
    ----------
    xyz_path : str
        Path to the XYZ file.

    Returns
    -------
    int
        The number of atoms in the file.

    Raises
    ------
    FileNotFoundError
        If the file does not exist.
    ValueError
        If the format is invalid or coordinates are missing.
    """
    if not os.path.isfile(xyz_path):
        raise FileNotFoundError(f"XYZ input file not found: {xyz_path}")

    with open(xyz_path, "r", encoding="utf-8") as xyz_file:
        lines = xyz_file.readlines()

    if len(lines) < 2:
        raise ValueError(f"XYZ file is incomplete: {xyz_path}")

    try:
        atom_count = int(lines[0].strip())
    except ValueError as error:
        raise ValueError(f"First XYZ line must be an atom count: {xyz_path}") from error

    if atom_count <= 0 or len(lines) < atom_count + 2:
        raise ValueError(f"XYZ file does not contain {atom_count} atoms: {xyz_path}")

    for line_number, line in enumerate(lines[2:atom_count + 2], start=3):
        fields = line.split()
        if len(fields) < 4:
            raise ValueError(f"Invalid XYZ coordinate at {xyz_path}:{line_number}")
        try:
            [float(value) for value in fields[1:4]]
        except ValueError as error:
            raise ValueError(f"Invalid XYZ coordinate at {xyz_path}:{line_number}") from error

    return atom_count


def _build_hill_formula(atom_counts: Counter) -> str:
    """Build molecular formula using Hill system notation (C first, then H, then alphabetical)."""
    parts = []
    if "C" in atom_counts:
        parts.append(f"C{atom_counts['C'] if atom_counts['C'] > 1 else ''}")
        if "H" in atom_counts:
            parts.append(f"H{atom_counts['H'] if atom_counts['H'] > 1 else ''}")

    other_elements = sorted(
        [el for el in atom_counts if (el != "C" and (el != "H" or "C" not in atom_counts))]
    )
    for el in other_elements:
        count = atom_counts[el]
        parts.append(f"{el}{count if count > 1 else ''}")
    return "".join(parts)


def read_xyz(xyz_path: str) -> XYZStructure:
    """
    Read an XYZ file and parse into a typed XYZStructure.

    Parameters
    ----------
    xyz_path : str
        Path to the XYZ file.

    Returns
    -------
    XYZStructure
        Parsed molecular structure.
    """
    atom_count = validate_xyz_file(xyz_path)
    with open(xyz_path, "r", encoding="utf-8") as f:
        lines = f.readlines()

    comment = lines[1].strip() if len(lines) > 1 else ""
    atoms: List[str] = []
    coords: List[List[float]] = []

    for line in lines[2:atom_count + 2]:
        parts = line.split()
        atoms.append(parts[0].capitalize())
        coords.append([float(parts[1]), float(parts[2]), float(parts[3])])

    coord_arr = np.array(coords, dtype=np.float64)
    counter = Counter(atoms)
    formula = _build_hill_formula(counter)

    # Compute molecular weight
    mw = sum(ATOMIC_WEIGHTS.get(atom.upper(), 0.0) for atom in atoms)

    return XYZStructure(
        atoms=atoms,
        coordinates=coord_arr,
        comment=comment,
        atom_count=atom_count,
        formula=formula,
        molecular_weight=mw,
    )


def write_xyz(
    xyz_path: str,
    atoms: List[str],
    coordinates: np.ndarray,
    comment: str = "Generated by NLE-Predictor",
) -> None:
    """
    Write atoms and 3D coordinates to an XYZ file.

    Parameters
    ----------
    xyz_path : str
        Destination path.
    atoms : List[str]
        List of chemical symbols.
    coordinates : np.ndarray
        Shape (N, 3) coordinate array.
    comment : str
        Comment line text.
    """
    if len(atoms) != len(coordinates):
        raise ValueError("Atom count and coordinate array length must match.")

    parent = os.path.dirname(xyz_path)
    if parent:
        os.makedirs(parent, exist_ok=True)

    with open(xyz_path, "w", encoding="utf-8") as f:
        f.write(f"{len(atoms)}\n")
        f.write(f"{comment}\n")
        for atom, (x, y, z) in zip(atoms, coordinates, strict=True):
            f.write(f"{atom:<3} {x:14.8f} {y:14.8f} {z:14.8f}\n")


def calculate_rmsd(coords_p: np.ndarray, coords_q: np.ndarray) -> float:
    """
    Calculate the minimal Root Mean Square Deviation (RMSD) between two
    equisized coordinate sets using the optimal Kabsch rotation algorithm.

    Parameters
    ----------
    coords_p : np.ndarray
        Target coordinate set of shape (N, 3).
    coords_q : np.ndarray
        Mobile coordinate set of shape (N, 3).

    Returns
    -------
    float
        Optimal RMSD in Angstroms.
    """
    if coords_p.shape != coords_q.shape:
        raise ValueError(f"Shape mismatch in RMSD: {coords_p.shape} vs {coords_q.shape}")
    if len(coords_p) == 0:
        return 0.0

    # Center coordinates at centroid
    p_centered = coords_p - np.mean(coords_p, axis=0)
    q_centered = coords_q - np.mean(coords_q, axis=0)

    # Kabsch covariance matrix H = Q^T * P
    covariance = np.dot(q_centered.T, p_centered)

    # Singular Value Decomposition
    v_matrix, s_vals, w_trans = np.linalg.svd(covariance)

    # Check for reflection
    d = np.linalg.det(np.dot(v_matrix, w_trans))
    if d < 0.0:
        v_matrix[:, -1] *= -1.0

    # Optimal rotation matrix
    rotation = np.dot(v_matrix, w_trans)

    # Rotate q_centered onto p_centered
    q_rotated = np.dot(q_centered, rotation)

    # Calculate RMSD
    diff = p_centered - q_rotated
    return float(np.sqrt(np.mean(np.sum(diff * diff, axis=1))))
